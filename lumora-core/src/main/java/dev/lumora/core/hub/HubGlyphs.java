    private HubGlyphs() {
    }

    private static void put(String name, String... rows) {
        if (rows.length != SIZE) {
            throw new IllegalStateException("glyph " + name + ": " + rows.length + " rows");
        }
        for (String r : rows) {
            if (r.length() != SIZE) {
                throw new IllegalStateException("glyph " + name + ": row " + r);
            }
        }
        GLYPHS.put(name, rows);
    }

    public static boolean has(String name) {
        return GLYPHS.containsKey(name);
    }

    /** Draws the glyph with its top left corner at (x, y); unknown names draw nothing. */
    public static void draw(HudGraphics g, String name, int x, int y, int color) {
        String[] rows = GLYPHS.get(name);
        if (rows == null) {
            return;
        }
        for (int r = 0; r < SIZE; r++) {
            String row = rows[r];
            int c = 0;
            while (c < SIZE) {
                if (row.charAt(c) != '#') {
                    c++;
                    continue;
                }
                int start = c;
                while (c < SIZE && row.charAt(c) == '#') {
                    c++;
                }
                g.fill(x + start, y + r, x + c, y + r + 1, color);
            }
        }
    }
