package dev.lumora.loader.impl;

import java.io.IOException;
import java.io.InputStream;
import java.net.JarURLConnection;
import java.net.URL;
import java.net.URLClassLoader;
import java.net.URLConnection;
import java.security.CodeSigner;
import java.security.CodeSource;
import java.security.ProtectionDomain;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;

/**
 * Class loader of the game: the Minecraft client jar and the Lumora client jar. Classes found in these jars are loaded
 * here (not by the parent), and every one of them passes the mixin transformer before it is defined, so the client's
 * mixins apply to Minecraft. Everything else (Java, the libraries on the class path such as LWJGL, Gson, Netty, Log4j,
 * and the loader itself with Mixin and ASM) comes from the parent.
 */
public final class GameClassLoader extends URLClassLoader {
    static {
        ClassLoader.registerAsParallelCapable();
    }

    /** Always from the parent: the loader, Mixin and ASM must exist exactly once. */
    private static final List<String> PARENT_ONLY = List.of("java.", "javax.", "jdk.", "sun.", "com.sun.",
            "dev.lumora.loader.", "org.spongepowered.", "org.objectweb.asm.");

    /** Prefix of the classes Mixin generates at runtime (e.g. the argument bundles of {@code @ModifyArgs}). */
    static final String SYNTHETIC = "org.spongepowered.asm.synthetic.";

    /** Transforms raw class bytes (the mixin transformer once it is ready). */
    public interface Transformer {
        byte[] transform(String name, byte[] bytes);

        /** Bytes of a class Mixin generates itself, or null. */
        default byte[] generate(String name) {
            return null;
        }
    }

    private volatile Transformer transformer;
    private final Map<URL, ProtectionDomain> domains = new ConcurrentHashMap<>();

    public GameClassLoader(URL[] jars, ClassLoader parent) {
        super("lumora-game", jars, parent);
    }

    void transformer(Transformer t) {
        this.transformer = t;
    }

    static boolean parentOnly(String name) {
        for (String p : PARENT_ONLY) {
            if (name.startsWith(p)) {
                return true;
            }
        }
        return false;
    }

    @Override
    protected Class<?> loadClass(String name, boolean resolve) throws ClassNotFoundException {
        synchronized (getClassLoadingLock(name)) {
            Class<?> c = findLoadedClass(name);
            if (c == null && name.startsWith(SYNTHETIC)) {
                // generated by Mixin, belongs next to the game classes that use it
                Transformer t = transformer;
                byte[] generated = t == null ? null : t.generate(name);
                if (generated == null) {
                    throw new ClassNotFoundException(name);
                }
                c = defineClass(name, generated, 0, generated.length);
            }
            if (c == null && !parentOnly(name)) {
                URL url = findResource(name.replace('.', '/') + ".class");
                if (url != null) {
                    c = define(name, url);
                }
            }
            if (c == null) {
                c = getParent().loadClass(name);
            }
            if (resolve) {
                resolveClass(c);
            }
            return c;
        }
    }

    private Class<?> define(String name, URL url) throws ClassNotFoundException {
        byte[] bytes;
        try (InputStream in = url.openStream()) {
            bytes = in.readAllBytes();
        } catch (IOException e) {
            throw new ClassNotFoundException(name + ": " + e.getMessage(), e);
        }
        Transformer t = transformer;
        if (t != null) {
            bytes = t.transform(name, bytes);
        }
        int dot = name.lastIndexOf('.');
        if (dot > 0) {
            String pkg = name.substring(0, dot);
            if (getDefinedPackage(pkg) == null) {
                try {
                    definePackage(pkg, null, null, null, null, null, null, null);
                } catch (IllegalArgumentException alreadyDefined) {
                    // defined by a parallel load
                }
            }
        }
        return defineClass(name, bytes, 0, bytes.length, domain(url));
    }

    /** One protection domain per jar, with the jar as code source (Minecraft looks up its own jar that way). */
    private ProtectionDomain domain(URL classUrl) {
        URL jar = classUrl;
        try {
            URLConnection c = classUrl.openConnection();
            if (c instanceof JarURLConnection j) {
                jar = j.getJarFileURL();
            }
        } catch (IOException ignored) {
            // fall back to the class URL
        }
        return domains.computeIfAbsent(jar, u -> new ProtectionDomain(new CodeSource(u, (CodeSigner[]) null), null, this, null));
    }

    /** The untransformed bytes of a class: from the game jars, else from the parent (JDK, libraries). Null if none. */
    public byte[] rawBytes(String name) throws IOException {
        String path = name.replace('.', '/') + ".class";
        URL url = parentOnly(name) ? null : findResource(path);
        InputStream in = url != null ? url.openStream() : getParent().getResourceAsStream(path);
        if (in == null) {
            in = ClassLoader.getSystemResourceAsStream(path);
        }
        if (in == null) {
            return null;
        }
        try (InputStream s = in) {
            return s.readAllBytes();
        }
    }

    public boolean isClassLoaded(String name) {
        synchronized (getClassLoadingLock(name)) {
            return findLoadedClass(name) != null;
        }
    }
}
